export function getProblemsByTopic(topicId: string): Problem[] {
  return PROBLEMS.filter((p) => p.topicId === topicId && p.answerType !== 'equationRepair');
}

export function getEquationRepairs(): Problem[] {
  return PROBLEMS.filter((p) => p.answerType === 'equationRepair');
}

export function getProblem(id: string): Problem | undefined {
  return PROBLEMS.find((p) => p.id === id);
}

export function getRandomProblem(
  topicId: string,
  excludeIds: string[] = [],
  difficulty?: 'beginner' | 'intermediate' | 'advanced',
): Problem | undefined {
  let pool = getProblemsByTopic(topicId).filter((p) => !excludeIds.includes(p.id));
  if (difficulty) {
    const narrowed = pool.filter((p) => p.difficulty === difficulty);
    if (narrowed.length > 0) pool = narrowed;
  }
  if (pool.length === 0) pool = getProblemsByTopic(topicId);
  return pool[Math.floor(Math.random() * pool.length)];
}
